-- ============================================
-- УДАЛЕНИЕ СТАДИИ "call" (Звонок) ИЗ DEALS
-- ============================================
-- Этот SQL обновляет все сделки со стадией "call" на стадию "new"
-- и удаляет стадию "call" из использования
-- ============================================

-- Обновляем все сделки со стадией "call" на стадию "new"
UPDATE deals 
SET stage = 'new' 
WHERE stage = 'call';

-- Проверяем результат
SELECT 
  stage,
  COUNT(*) as count
FROM deals
GROUP BY stage
ORDER BY stage;

