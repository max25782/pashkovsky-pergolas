/**
 * Угол поворота SVG-подписи вдоль стороны, по экранным (не мировым!) координатам.
 *
 * Почему не через мировой angleDeg с ручной компенсацией Y-flip: любая попытка
 * "отменить" переворот через scale(1,-1) даёт зеркальный (задом наперёд читаемый)
 * текст — сам SVG-канвас уже в системе, где Y растёт вниз, и rotate() в этой
 * системе работает корректно без какой-либо компенсации. Поэтому угол считается
 * напрямую из экранных дельт (после worldToScreen), а не из мирового angleDeg.
 *
 * Отдельная проблема — не переворот, а читаемость: сырой screen-угол для сторон,
 * идущих на экране "справа налево" (|angle| > 90°), даёт текст вверх ногами.
 * Разворачиваем такие на 180° — подпись остаётся на той же линии, но читается
 * слева-направо. Побочный эффект: смещение подписи (см. FixedEdges.tsx) может
 * оказаться на другой стороне линии в зависимости от угла — это ожидаемо для
 * CAD-подобных обозначений, не баг.
 */
export function readableLabelAngleDeg(dxScreen: number, dyScreen: number): number {
  const raw = (Math.atan2(dyScreen, dxScreen) * 180) / Math.PI
  if (raw > 90 || raw < -90) {
    // Нормализуем в (-180, 180] — иначе raw=180° даёт flipped=360°: для SVG
    // rotate() это визуально то же самое, что 0°, но как число — не то же самое.
    const flipped = raw + 180
    return flipped > 180 ? flipped - 360 : flipped
  }
  return raw
}
