/**
 * Select system prompt based on analytics mode
 */
export function selectSystemPrompt(mode: AnalyticsMode): string {
  switch (mode) {
    case 'leads':
      return LEADS_ANALYST_PROMPT
    case 'deals':
      return DEALS_ANALYST_PROMPT
    case 'finance':
      return FINANCE_ANALYST_PROMPT
    case 'manager':
      return MANAGER_ANALYST_PROMPT
    default:
      // Fallback to manager prompt for unknown modes
      return MANAGER_ANALYST_PROMPT
  }
}

